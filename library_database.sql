CREATE TABLE Books (
    book_id           NUMBER GENERATED BY DEFAULT AS IDENTITY,
    title             VARCHAR2(200) NOT NULL,
    author            VARCHAR2(150) NOT NULL,
    publication_year  NUMBER(4),
    available_copies  NUMBER DEFAULT 1 NOT NULL,
    CONSTRAINT pk_books PRIMARY KEY (book_id),
    CONSTRAINT chk_books_copies CHECK (available_copies >= 0),
    CONSTRAINT chk_books_year CHECK (
        publication_year IS NULL OR
        publication_year BETWEEN 1000 AND 9999
    )
);

CREATE TABLE Members (
    member_id  NUMBER GENERATED BY DEFAULT AS IDENTITY,
    f_name     VARCHAR2(100) NOT NULL,
    l_name     VARCHAR2(100) NOT NULL,
    email      VARCHAR2(254) NOT NULL,
    CONSTRAINT pk_members PRIMARY KEY (member_id),
    CONSTRAINT uq_members_email UNIQUE (email)
);

CREATE TABLE Users (
    user_id       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    username      VARCHAR2(100) NOT NULL,
    user_role     VARCHAR2(30) NOT NULL,
    member_id     NUMBER,
    CONSTRAINT pk_users PRIMARY KEY (user_id),
    CONSTRAINT uq_users_username UNIQUE (username),
    CONSTRAINT chk_users_role CHECK (
        user_role IN ('ADMIN', 'MODERATOR', 'MEMBER', 'GUEST')
    ),
    CONSTRAINT fk_users_member FOREIGN KEY (member_id)
        REFERENCES Members(member_id)
);

CREATE TABLE Borrowing (
    borrow_id   NUMBER GENERATED BY DEFAULT AS IDENTITY,
    book_id     NUMBER NOT NULL,
    member_id   NUMBER NOT NULL,
    borrowdate  DATE DEFAULT SYSDATE NOT NULL,
    duedate     DATE NOT NULL,
    returndate  DATE,
    CONSTRAINT pk_borrowing PRIMARY KEY (borrow_id),
    CONSTRAINT fk_borrowing_book FOREIGN KEY (book_id)
        REFERENCES Books(book_id),
    CONSTRAINT fk_borrowing_member FOREIGN KEY (member_id)
        REFERENCES Members(member_id),
    CONSTRAINT chk_borrowing_dates CHECK (
        returndate IS NULL OR returndate >= borrowdate
    ),
    CONSTRAINT chk_borrowing_due_date CHECK (duedate >= borrowdate)
);

