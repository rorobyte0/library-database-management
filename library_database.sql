-- 4. QUERIES
-- ------------------------------------------------------------

-- 4.1 Rank books by number of recorded borrowing transactions.
SELECT
    b.book_id,
    b.title,
    COUNT(br.borrow_id) AS times_borrowed
FROM Books b
JOIN Borrowing br ON br.book_id = b.book_id
GROUP BY b.book_id, b.title
ORDER BY times_borrowed DESC, b.title;

-- 4.2 Retrieve only the required column(s).
SELECT title
FROM Books
WHERE author = 'George Orwell';

-- 4.3 Find members with overdue books that have not been returned.
SELECT
    m.member_id,
    m.f_name,
    m.l_name,
    br.duedate
FROM Members m
JOIN Borrowing br ON br.member_id = m.member_id
WHERE br.duedate < SYSDATE
  AND br.returndate IS NULL
ORDER BY br.duedate;

-- 4.4 Alternative using EXISTS to return each matching member once.
SELECT
    m.member_id,
    m.f_name,
    m.l_name
FROM Members m
WHERE EXISTS (
    SELECT 1
    FROM Borrowing br
    WHERE br.member_id = m.member_id
      AND br.duedate < SYSDATE
      AND br.returndate IS NULL
);

