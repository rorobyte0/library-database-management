-- ------------------------------------------------------------
-- 3. PL/SQL FUNCTION: CALCULATE OVERDUE FINE
-- Fine rate: 2 currency units per overdue day.
-- Unreturned books are calculated up to the current date.
-- ------------------------------------------------------------

CREATE OR REPLACE FUNCTION calculate_debt (
    p_borrow_id IN Borrowing.borrow_id%TYPE
) RETURN NUMBER
IS
    v_due_date    Borrowing.duedate%TYPE;
    v_return_date Borrowing.returndate%TYPE;
    v_days_late   NUMBER;
BEGIN
    SELECT duedate, returndate
    INTO v_due_date, v_return_date
    FROM Borrowing
    WHERE borrow_id = p_borrow_id;

    v_days_late := GREATEST(
        TRUNC(NVL(v_return_date, SYSDATE)) - TRUNC(v_due_date),
        0
    );

    RETURN v_days_late * 2;

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RETURN NULL;
END;
/

-- Test the function. SQL Developer will prompt for a borrowing ID.
DECLARE
    v_borrow_id Borrowing.borrow_id%TYPE := &borrow_id;
    v_debt      NUMBER;
BEGIN
    v_debt := calculate_debt(v_borrow_id);

    IF v_debt IS NULL THEN
        DBMS_OUTPUT.PUT_LINE('No borrowing record was found.');
    ELSE
        DBMS_OUTPUT.PUT_LINE('Calculated fine amount: ' || v_debt);
    END IF;
END;
